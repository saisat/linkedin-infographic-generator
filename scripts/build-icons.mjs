// Build skills/motion-infographic/kit/icons.js from Lucide (lucide-static, ISC) for canvas drawing.
// Every SVG element becomes one path string in the 24 x 24 Lucide grid, so lib.js can stroke and draw it on.
//   npm run icons            (add a name to ICONS below, then rerun)
import { readFileSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const pkg = require('lucide-static/package.json');
const dir = new URL('../node_modules/lucide-static/icons/', import.meta.url);

export const ICONS = [
  // documents and media
  'file-text', 'folder', 'image', 'camera', 'video', 'film', 'play', 'mic', 'clapperboard', 'monitor-smartphone', 'smartphone',
  // writing and design
  'pen-line', 'type', 'palette', 'wand-sparkles', 'scissors', 'layers', 'sparkles',
  // thinking and strategy
  'lightbulb', 'brain', 'target', 'compass', 'puzzle', 'flag', 'search', 'eye', 'gauge', 'flask-conical',
  // people and organisations
  'user', 'users', 'user-check', 'building-2', 'briefcase', 'handshake', 'graduation-cap', 'book-open', 'award',
  // communication and flow
  'inbox', 'mail', 'send', 'message-square', 'link', 'globe', 'refresh-cw', 'repeat', 'upload', 'download',
  // work, time and results
  'calendar', 'clock', 'list-checks', 'circle-check', 'shield-check', 'rocket', 'zap', 'settings', 'wrench',
  'chart-column', 'chart-bar', 'trending-up',
];

const attrs = (s) => Object.fromEntries([...s.matchAll(/([a-z0-9-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v || 0);
function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': { const cx = n(a.cx), cy = n(a.cy), r = n(a.r); return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
    case 'ellipse': { const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry); return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': case 'polygon': { const p = a.points.trim().split(/[\s,]+/).map(Number); let d = `M${p[0]} ${p[1]}`; for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`; return tag === 'polygon' ? d + 'Z' : d; }
    case 'rect': {
      const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height), r = Math.min(n(a.rx || a.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    default: throw new Error('unsupported element: ' + tag);
  }
}
const out = {};
for (const name of ICONS) {
  const svg = readFileSync(new URL(name + '.svg', dir), 'utf8').replace(/<!--.*?-->/gs, '');
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  out[name] = [...body.matchAll(/<(path|circle|ellipse|line|polyline|polygon|rect)\b([^>]*)\/?>/g)].map((m) => toPath(m[1], attrs(m[2])));
}
const bad = Object.entries(out).filter(([, ds]) => !ds.length || ds.some((d) => /undefined|NaN/.test(d)));
if (bad.length) throw new Error('bad icon paths: ' + bad.map(([k]) => k).join(', '));
const target = new URL('../skills/motion-infographic/kit/icons.js', import.meta.url);
writeFileSync(target, `// Generated by scripts/build-icons.mjs from lucide-static ${pkg.version} (ISC licence, https://lucide.dev). Do not edit by hand.
// Each icon is a list of SVG path strings on Lucide's 24 x 24 grid, drawn by Motion.icon().
window.ICONS = ${JSON.stringify(out)};
`);
console.log(`icons.js: ${ICONS.length} icons from lucide-static ${pkg.version}`);
